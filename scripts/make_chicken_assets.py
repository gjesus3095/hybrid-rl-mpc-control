def _fmt(values) -> str:
    return " ".join(f"{v:g}" for v in values)


def build_urdf() -> ET.Element:
    franka = ET.parse(FRANKA_URDF).getroot()
    robot = ET.Element("robot", name="ridgeback_franka_chicken")
    robot.append(ET.Comment(" Generated by scripts/make_chicken_assets.py; edit PARTS there, not this file. "))
    for name, rgba in COLORS.items():
        ET.SubElement(ET.SubElement(robot, "material", name=name), "color", rgba=_fmt(rgba))

    for link_name in ["base_link", *FRANKA_CHAIN]:
        link = ET.SubElement(robot, "link", name=link_name)
        if link_name == "base_link":  # the platform itself, so the URDF also describes the 0.4 x 0.4 m base
            collision = ET.SubElement(link, "collision", name="platform")
            ET.SubElement(collision, "origin", xyz=_fmt((X, 0, STOCK_HEIGHT / 2)), rpy="0 0 0")
            ET.SubElement(ET.SubElement(collision, "geometry"), "box", size=_fmt((*FOOTPRINT, STOCK_HEIGHT)))
        for name, mesh, xyz, rpy, scale, color in PARTS.get(link_name, []):
            visual = ET.SubElement(link, "visual", name=name)
            ET.SubElement(visual, "origin", xyz=_fmt(xyz), rpy=_fmt(rpy))
            ET.SubElement(ET.SubElement(visual, "geometry"), "mesh", filename=f"meshes/{mesh}", scale=_fmt(scale))
            ET.SubElement(visual, "material", name=color)

    mount = ET.SubElement(robot, "joint", name="arm_mount_joint", type="fixed")
    ET.SubElement(mount, "origin", xyz=_fmt((X, 0, STOCK_HEIGHT)), rpy="0 0 0")
    ET.SubElement(mount, "parent", link="base_link")
    ET.SubElement(mount, "child", link="panda_link0")
    chain = set(FRANKA_CHAIN)
    for joint in franka.findall("joint"):
        if joint.find("parent").get("link") in chain and joint.find("child").get("link") in chain:
            robot.append(copy.deepcopy(joint))
    ET.indent(robot)
    return robot


def main():
    meshes = ASSET_DIR / "meshes"
    meshes.mkdir(parents=True, exist_ok=True)
    write_obj(meshes / "sphere.obj", uv_sphere())
    write_obj(meshes / "cone.obj", cone())
    write_obj(meshes / "nest.obj", torus(major=0.165, minor=0.045))
    ET.ElementTree(build_urdf()).write(CHICKEN_URDF, encoding="unicode", xml_declaration=True)
    print(f"wrote {CHICKEN_URDF} and {sorted(p.name for p in meshes.iterdir())}")


if __name__ == "__main__":
    main()
